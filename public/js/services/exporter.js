// Seller package: STL + listing + printability report + pricing CSV + specs JSON.
import { PRINTERS, MARKETS } from "../config/catalog.js";
import { fmtHours } from "../core/utils.js";

// Binary STL, converted from the app's Y-up to the Z-up that slicers expect.
export function toSTL(m, label = "model") {
  const n = m.idx.length / 3, buf = new ArrayBuffer(84 + 50 * n), dv = new DataView(buf);
  const head = "ImageIT3D export: " + label;
  for (let i = 0; i < Math.min(80, head.length); i++) dv.setUint8(i, head.charCodeAt(i) & 0x7f);
  dv.setUint32(80, n, true);
  let o = 84; const P = m.pos;
  const vtx = i => [P[i * 3], -P[i * 3 + 2], P[i * 3 + 1]];
  for (let t = 0; t < n; t++) {
    const a = vtx(m.idx[t * 3]), b = vtx(m.idx[t * 3 + 1]), c = vtx(m.idx[t * 3 + 2]);
    const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]], v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
    const nx = u[1] * v[2] - u[2] * v[1], ny = u[2] * v[0] - u[0] * v[2], nz = u[0] * v[1] - u[1] * v[0], l = Math.hypot(nx, ny, nz) || 1;
    for (const f of [nx / l, ny / l, nz / l, ...a, ...b, ...c]) { dv.setFloat32(o, f, true); o += 4; }
    dv.setUint16(o, 0, true); o += 2;
  }
  return buf;
}

export function reportText({ state, current, colorName, dims }) {
  const A = current.analysis, E = current.evaluation;
  const verdict = { pass: "Ready to print", warn: "Printable with care", fail: "Not ready to print" }[E.level];
  return `PRINTABILITY REPORT: ${state.spec.name}\nGenerated by LaunchIT3D on ${new Date().toLocaleDateString()}\n\n` +
    `Printer: ${PRINTERS[state.printer].name}\nMaterial: ${state.material}, ${state.infill}% infill, color ${colorName}\n` +
    `Size: ${dims}\nVolume: ${(A.vol / 1000).toFixed(1)} cm3\nEstimated filament: ${E.grams.toFixed(0)} g\nEstimated print time: ${fmtHours(E.hours)}\n\n` +
    `Overall: ${verdict}\n\n` + E.checks.map(c => `[${c.l.toUpperCase()}] ${c.t}\n  ${c.d}`).join("\n\n") + "\n";
}

export function pricingCSV(P) {
  return "item,amount_usd\n" + P.rows.map(([k, v]) => `"${k}",${v.toFixed(2)}`).join("\n") +
    `\n"Cost to make one",${P.cost.toFixed(2)}\n\ntier,price_usd,fees_usd,you_keep_usd\n` +
    P.tiers.map(([n, t]) => `${n},${t.price.toFixed(2)},${t.fees.toFixed(2)},${t.keep.toFixed(2)}`).join("\n") +
    `\n\nmarketplace,"${P.market.name}"\nnote,"${P.market.note}"\n`;
}

export const listingText = l => `TITLE\n${l.title}\n\nDESCRIPTION\n${l.description}\n\nTAGS\n${l.tags}\n`;

export async function buildPackage({ state, current, colorName, dims, slug }) {
  if (typeof JSZip === "undefined") throw new Error("The zip tool didn't load. Download the model on its own instead.");
  const z = new JSZip();
  z.file(`${slug}.stl`, toSTL(current.mesh, state.spec.name));
  z.file("listing.txt", listingText(state.listing));
  z.file("printability-report.txt", reportText({ state, current, colorName, dims }));
  z.file("pricing.csv", pricingCSV(current.price));
  z.file("specs.json", JSON.stringify({
    app: "ImageIT3D + LaunchIT3D", spec: state.spec, letters: current.textInfo ? state.spec.text.content : null,
    color: colorName, printer: PRINTERS[state.printer].name, material: state.material, infill: state.infill, marketplace: MARKETS[state.market].name
  }, null, 2));
  return z.generateAsync({ type: "blob" });
}

export function downloadBlob(filename, data) {
  const blob = data instanceof Blob ? data : new Blob([data]);
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob); a.download = filename;
  document.body.append(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 10000);
}
